-- Roles, and real proof of who is calling.
--
-- THE PROBLEM THIS SOLVES.
-- Until now the app told the server which farmer it was, by putting
-- farmer_id in the request. The server believed it. For a farmer using their
-- own phone to read their own soil data, that is survivable.
--
-- It is not survivable for an officer dashboard. An officer can see other
-- people's data and correct it. If the browser can simply CLAIM to be a
-- department officer, then anybody who can type a web address is a
-- department officer. Identity has to be proved by the server.

-- ---------- PART 1: ROLES ----------
--
-- WHY OFFICERS LIVE IN THE farmers TABLE.
--
-- An officer has a name, a NIC, a mobile number, an email and a password,
-- which is exactly what the farmers table already holds. A separate officers
-- table would mean a second login endpoint, a second password hashing path
-- and a second set of account rules to keep in step.
--
-- Duplicated authentication is one of the easiest ways to end up with a
-- security hole: the copy nobody remembers is the one that never gets fixed.
-- An imperfect table name is a much smaller problem, so one table it is.
-- A later migration can rename it to "users" if the name starts to grate.

ALTER TABLE farmers
    ADD COLUMN role TEXT NOT NULL DEFAULT 'FARMER';

-- The database refuses any role we have not thought about. Our last safety
-- net, the same way districts_zone_check works in 003_add_zone.sql.
ALTER TABLE farmers
    ADD CONSTRAINT farmers_role_check
    CHECK (role IN ('FARMER', 'GN_OFFICER', 'DEPT_OFFICER'));

-- WHICH DIVISION a GN officer is responsible for.
--
-- NULL for farmers and for department officers: a farmer has no authority
-- over anybody, and a department officer sees the whole country. Only a
-- division officer is limited to one place, so only they need this.
ALTER TABLE farmers
    ADD COLUMN scope_division TEXT;

-- ---------- PART 2: SESSIONS ----------
--
-- WHY A TABLE AND NOT A JWT.
--
-- A JWT is a signed note the server hands out and then trusts on sight. It
-- needs no lookup, which is why large systems like it. But it also cannot be
-- taken back: if an officer leaves, or a token is stolen, that note keeps
-- working until it expires.
--
-- A row in a table can be deleted. Logging out, or revoking an officer's
-- access, becomes one DELETE. It costs one indexed lookup per request, which
-- for a system this size is nothing. It also needs no new library, and it is
-- far easier to explain in a report than JWT signing.

CREATE TABLE sessions (
    -- The token itself IS the key. It is a long random string generated by
    -- the server, never anything guessable like a farmer id.
    token      TEXT PRIMARY KEY,

    -- ON DELETE CASCADE: deleting an account kills its sessions with it.
    -- Otherwise a deleted officer's token would still open doors.
    farmer_id  INTEGER NOT NULL
               REFERENCES farmers(farmer_id) ON DELETE CASCADE,

    created_at TIMESTAMP NOT NULL DEFAULT NOW(),

    -- EVERY SESSION ENDS.
    -- A token that never expires is a password that can never be changed.
    expires_at TIMESTAMP NOT NULL
);

-- Finding a farmer's sessions, so logging out everywhere is one statement.
CREATE INDEX idx_sessions_farmer ON sessions(farmer_id);

-- Clearing out sessions that have already expired.
CREATE INDEX idx_sessions_expires ON sessions(expires_at);
